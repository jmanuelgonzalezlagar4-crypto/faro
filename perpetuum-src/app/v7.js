const { chromium, open } = require('./pw.js');
(async () => {
  const browser = await chromium.launch();
  const { ctx, page, errors } = await open(browser, 'debug.html', { width: 390, height: 844 }, 'light', { touch: true });
  await page.evaluate(() => localStorage.setItem('taller-perpetuum.bienvenida', '1'));
  await page.click('#welEmpty').catch(() => {});
  // entrada por la paleta
  await page.click('.tool[data-tool="add"]'); await page.waitForTimeout(200);
  await page.screenshot({ path: 'v7-0-paleta.png' });
  await page.click('[data-kind="scan"]'); await page.waitForSelector('label[for="scanFile"]');
  const fc = page.waitForEvent('filechooser');
  await page.click('label[for="scanFile"]');
  const chooser = await fc; await chooser.setFiles(process.argv[2] || 'maqueta-prueba2.jpg');
  await page.waitForTimeout(150);
  await page.screenshot({ path: 'v7-1-busy.png' });
  await page.waitForFunction(() => !document.getElementById('scanBusy') || document.getElementById('scanBusy').hidden, null, { timeout: 15000 });
  await page.waitForTimeout(200);
  await page.screenshot({ path: 'v7-2-rueda.png' });
  console.log('paso1:', (await page.locator('#scanCtl .scan-say').innerText()));
  await page.fill('#sc_diam', '60'); await page.dispatchEvent('#sc_diam', 'change'); await page.waitForTimeout(100);
  await page.click('#sc_next'); await page.waitForTimeout(200);
  await page.screenshot({ path: 'v7-3-pesas.png' });
  console.log('paso2:', (await page.locator('#scanCtl .scan-say').innerText()));
  await page.click('#sc_next'); await page.waitForTimeout(200);
  await page.screenshot({ path: 'v7-4-montaje.png', fullPage: false });
  console.log('paso3:', (await page.locator('#scanCtl .scan-sum').innerText()));
  await page.locator('#sc_make').scrollIntoViewIfNeeded();
  await page.screenshot({ path: 'v7-4b-montaje.png' });
  await page.click('#sc_make'); await page.waitForTimeout(600);
  const info = await page.evaluate(() => { const d = window.__T.design; const c = {}; d.parts.forEach(p => c[p.kind] = (c[p.kind] || 0) + 1);
    const w = d.parts[0]; const pins = d.parts.filter(p => p.kind === 'pin' && p.mode === 'limits').map(p => p.lo + '/' + p.hi);
    const balls = d.parts.filter(p => p.kind === 'ball').map(b => [Math.round(b.x * 100), Math.round(b.y * 100), Math.round(b.r * 1000), b.m]);
    return { c, wheel: [w.r, w.m, w.style, w.bearing], pins, balls, photo: d.photo }; });
  console.log(JSON.stringify(info));
  console.log('toast:', await page.locator('#toast').innerText());
  await page.screenshot({ path: 'v7-5-banco.png' });
  await page.click('#playBtn'); await page.waitForTimeout(5000);
  await page.screenshot({ path: 'v7-6-prueba.png' });
  console.log('veredicto:', await page.evaluate(() => { const w = window.__T.world || (window.__T.info && window.__T.info.world); return w ? JSON.stringify(w.balance ? w.balance() : null) : 'n/a'; }));
  console.log('errores:', errors);
  await browser.close();
})();
